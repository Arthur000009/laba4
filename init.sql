BEGIN;
DROP TABLE IF EXISTS operation_guard;
DROP TABLE IF EXISTS shipment_assignments CASCADE;
DROP TABLE IF EXISTS stops CASCADE;
DROP TABLE IF EXISTS shipments CASCADE;
DROP TABLE IF EXISTS routes CASCADE;
DROP TABLE IF EXISTS users CASCADE;

CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name VARCHAR(255) NOT NULL,
                       email VARCHAR(255) NOT NULL,
                        password_hash VARCHAR(100) NOT NULL,
                        role VARCHAR(30) NOT NULL CHECK (role IN ('CLIENT', 'DISPATCHER')),
                        account_status VARCHAR(30) NOT NULL CHECK (account_status IN ('ACTIVE', 'BLOCKED')),
                        CONSTRAINT chk_users_normalized_email CHECK (email = lower(trim(email))),
                       CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE routes (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        date DATE NOT NULL,
                        max_weight DOUBLE PRECISION NOT NULL,
                        status VARCHAR(255) NOT NULL,
                        CONSTRAINT chk_routes_max_weight CHECK (max_weight > 0),
                        CONSTRAINT chk_routes_status CHECK (status IN ('PLANNED', 'IN_PROGRESS', 'COMPLETED'))
);

CREATE TABLE stops (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       route_id BIGINT NOT NULL,
                       address VARCHAR(255) NOT NULL,
                       sequence_number INTEGER NOT NULL,
                       CONSTRAINT chk_stops_sequence CHECK (sequence_number > 0),
                       CONSTRAINT uk_stop_route_sequence UNIQUE (route_id, sequence_number),
                       CONSTRAINT fk_stops_route FOREIGN KEY (route_id) REFERENCES routes (id) ON DELETE CASCADE
);

CREATE TABLE shipments (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           created_at TIMESTAMP(6) NOT NULL,
                           sender_id BIGINT NOT NULL,
                           address VARCHAR(255) NOT NULL,
                           weight DOUBLE PRECISION NOT NULL,
                           status VARCHAR(255) NOT NULL,
                           CONSTRAINT chk_shipments_weight CHECK (weight > 0),
                           CONSTRAINT chk_shipments_status CHECK (status IN ('CREATED', 'ASSIGNED', 'IN_TRANSIT', 'DELIVERED', 'CANCELLED')),
                           CONSTRAINT fk_shipments_sender FOREIGN KEY (sender_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE shipment_assignments (
                                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      shipment_id BIGINT NOT NULL,
                                      stop_id BIGINT NOT NULL,
                                      status VARCHAR(255) NOT NULL,
                                      CONSTRAINT uk_assignment_shipment UNIQUE (shipment_id),
                                      CONSTRAINT chk_assignments_status CHECK (status IN ('ASSIGNED', 'IN_TRANSIT', 'DELIVERED')),
                                      CONSTRAINT fk_assignments_shipment FOREIGN KEY (shipment_id) REFERENCES shipments (id) ON DELETE CASCADE,
                                      CONSTRAINT fk_assignments_stop FOREIGN KEY (stop_id) REFERENCES stops (id) ON DELETE CASCADE
);

CREATE TABLE operation_guard (id BIGINT PRIMARY KEY CHECK (id = 1));
